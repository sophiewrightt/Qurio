const assert = require('node:assert/strict');
const fs = require('node:fs');
const { createHarness } = require('./component-harness.cjs');
const lib = createHarness('components/AvatarGreeting.tsx', { enabled: false });
const ts = require('typescript');
const greetings = {};
new Function('exports', ts.transpileModule(fs.readFileSync('data/greetings.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(greetings);
const { greetingMessages: messages, eligibleGreetings, chooseGreeting, easterSunday, isValidBirthday } = greetings;
assert.equal(messages.anytime.length, 28);
assert.equal(messages.morning.length, 3);
assert.equal(eligibleGreetings(new Date(2026, 8, 25, 11, 59)).length, 31);
assert.deepEqual(eligibleGreetings(new Date(2026, 8, 25, 12)), messages.anytime);
assert.deepEqual(eligibleGreetings(new Date(2026, 8, 25, 0)), [...messages.morning, ...messages.anytime]);
for (let i = 0; i < 31; i++) assert.equal(chooseGreeting(new Date(2026, 8, 25, 9), undefined, () => (i + .5) / 31), [...messages.morning, ...messages.anytime][i]);
assert.equal(chooseGreeting(new Date(2026, 11, 25, 9)), 'Merry Christmas!');
assert.equal(chooseGreeting(new Date(2026, 11, 25, 9), { day: 25, month: 12 }), 'Happy birthday');
assert.deepEqual(easterSunday(2026), { day: 5, month: 4 });
assert.deepEqual(easterSunday(2027), { day: 28, month: 3 });
assert.equal(chooseGreeting(new Date(2026, 3, 5, 9)), 'Happy Easter!');
assert.equal(chooseGreeting(new Date(2027, 2, 28, 23)), 'Happy Easter!');
assert(!eligibleGreetings(new Date(2026, 3, 6, 9)).includes('Happy Easter!'));
assert(isValidBirthday({ day: 29, month: 2 }));
for (const birthday of [{ day: 31, month: 4 }, { day: 30, month: 2 }, { day: 0, month: 12 }, { day: 2, month: 13 }, { day: 1.5, month: 1 }]) assert(!isValidBirthday(birthday));
assert.equal(chooseGreeting(new Date(2028, 1, 29), { day: 29, month: 2 }), 'Happy birthday');
assert(!eligibleGreetings(new Date(2027, 1, 28), { day: 29, month: 2 }).includes('Happy birthday'));

const props = { enabled: false };
const bubble = createHarness('components/AvatarGreeting.tsx', props);
assert.equal(bubble.nodes('Text').length, 0);
assert.deepEqual(bubble.pendingTimeouts(), [], 'No timer runs under the loading cover');
props.enabled = true; bubble.render();
assert.equal(bubble.nodes('Text').length, 1);
const selected = bubble.nodes('Text')[0].children.join('');
assert.deepEqual(bubble.pendingTimeouts(), [4500]);
bubble.render(); assert.equal(bubble.nodes('Text')[0].children.join(''), selected, 'Renders do not reroll the greeting');
props.enabled = false; assert.equal(bubble.nodes('Text').length, 0);
props.enabled = true; assert.equal(bubble.nodes('Text')[0].children.join(''), selected);
bubble.timeout(); assert.equal(bubble.nodes('Text').length, 1, 'Text remains mounted during fade-out');
bubble.flight(); assert.equal(bubble.nodes('Text').length, 0);
bubble.render(); assert.equal(bubble.nodes('Text').length, 0, 'Expired greetings stay hidden for the rest of the visit');
const returnVisit = createHarness('components/AvatarGreeting.tsx', { enabled: true });
returnVisit.render(); assert.equal(returnVisit.nodes('Text').length, 1, 'A new Home mount greets again');
returnVisit.unmount(); assert.deepEqual(returnVisit.pendingTimeouts(), [], 'Leaving Home cancels the timer');
const leavingDuringFade = createHarness('components/AvatarGreeting.tsx', { enabled: true });
leavingDuringFade.render(); leavingDuringFade.nodes('Text'); leavingDuringFade.timeout();
const lateFade = leavingDuringFade.peekFlight();
leavingDuringFade.unmount(); lateFade({ finished: true });
assert.equal(leavingDuringFade.nodes('Text').length, 1, 'Cancelled fade callback must not update an unmounted greeting');
lib.unmount(); bubble.unmount();

let saved = 'untouched', closed = 0;
const profile = createHarness('components/ProfileModal.tsx', { onSave(value) { saved = value; }, onClose() { closed++; } });
const input = label => profile.nodes('TextInput').find(n => n.props.accessibilityLabel === label);
const save = () => profile.nodes('PrimaryButton').find(n => n.props.label === 'Save profile').props.onPress();
input('Birthday day').props.onChangeText('31'); input('Birthday month').props.onChangeText('4'); save();
assert.equal(saved, 'untouched'); assert.equal(closed, 0); assert(profile.nodes('Text').some(n => n.props.accessibilityRole === 'alert'));
input('Birthday day').props.onChangeText('29'); input('Birthday month').props.onChangeText('2'); save();
assert.deepEqual(saved, { day: 29, month: 2 }); assert.equal(closed, 1);
input('Birthday day').props.onChangeText(''); input('Birthday month').props.onChangeText(''); save(); assert.equal(saved, undefined);

const homeProps = { xp: 120, collected: false, completed: [], onContinue() {}, onSelectLesson() {} };
const home = createHarness('screens/HomeScreen.tsx', homeProps);
assert.equal(home.nodes('AvatarGreeting').length, 0, 'No avatar, no greeting');
homeProps.collected = true; assert.equal(home.nodes('AvatarGreeting').length, 1);
home.nodes('Pressable').find(n => n.props.accessibilityLabel === 'Open settings, Username, Level 1').props.onPress();
home.nodes('Pressable').find(n => n.children.some(child => child?.children?.includes('Profile & birthday'))).props.onPress();
assert.equal(home.nodes('ProfileModal').length, 1); assert.equal(home.nodes('AvatarGreeting')[0].props.enabled, false);
assert(!fs.readFileSync('screens/HomeScreen.tsx', 'utf8').includes('Good to see you, explorer'));
const app = createHarness('App.tsx');
app.nodes('HomeScreen')[0].props.onBirthdayChange({ day: 25, month: 9 });
app.nodes('HomeScreen')[0].props.onSelectLesson(2); app.nodes('LessonEntryModal')[0].props.onPlay();
app.nodes('LessonNavigationProvider')[0].props.onHome();
assert.deepEqual(app.nodes('HomeScreen')[0].props.birthday, { day: 25, month: 9 }, 'Birthday survives lesson navigation');
console.log('PASS: greeting pools, local time/noon boundary, birthdays, moving Easter, collisions, expiry, cleanup, avatar gate and profile validation');
