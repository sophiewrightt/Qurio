const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const { createHarness } = require('./component-harness.cjs');
const lib = {};
new Function('exports', ts.transpileModule(fs.readFileSync('data/dictionary.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(lib);
const { dictionaryId, recordDictionaryEntry: add, dictionaryCopyVisible: visible, watchDictionaryCopy: watch } = lib;
const empty = [];
assert.equal(add(empty, '', 'A definition'), empty);
assert.equal(add(empty, 'Spin', '  '), empty);
const one = add(empty, ' Spin ', ' Built-in property. ');
assert.equal(empty.length, 0);
assert.equal(one.length, 1);
assert.equal(add(one, 'Spin', 'Built-in property.'), one);
assert.equal(add(one, 'Spin', 'Another encountered definition.').length, 1);
assert.equal(dictionaryId(' Bell’s  theorem '), dictionaryId("bell's theorem"));
assert.equal(add(add([], 'Bell’s theorem', 'First'), "Bell's theorem", 'Second').length, 1);
const viewport = { width: 390, height: 800 };
assert(visible({ x: 20, y: 100, width: 300, height: 200 }, viewport));
for (const rect of [{ x: 20, y: 801, width: 300, height: 200 }, { x: 20, y: -210, width: 300, height: 200 }, { x: 20, y: 700, width: 300, height: 200 }, { x: -400, y: 100, width: 300, height: 200 }, { x: 0, y: 0, width: 0, height: 0 }]) assert(!visible(rect, viewport));
assert(visible({ x: 20, y: -100, width: 300, height: 1200 }, viewport), 'Large accessibility text can still be discovered');
let active = true, rect = { x: 20, y: 900, width: 300, height: 200 }, tick, stopped = 0, unlocked = 0, delayed;
const options = { measure: done => done(rect), viewport: () => viewport, isActive: () => active, onSeen: () => unlocked++, schedule: callback => { tick = callback; return () => stopped++; } };
const cleanup = watch(options);
tick(); assert.equal(unlocked, 0, 'Mounting offscreen is not discovery');
rect.y = 100; tick(); rect.y = 900; tick(); assert.equal(unlocked, 0, 'A quick scroll past does not unlock');
rect.y = 100; active = false; tick(); tick(); assert.equal(unlocked, 0, 'Background tabs cannot unlock');
active = true; tick(); tick(); assert.equal(unlocked, 1); assert.equal(stopped, 1);
tick(); assert.equal(unlocked, 1, 'Discovery is one-shot'); cleanup();
const cancel = watch({ ...options, measure: done => { delayed = done; } });
cancel(); delayed(rect); assert.equal(unlocked, 1, 'Late native measurements after unmount cannot unlock');

const app = createHarness('App.tsx');
assert.deepEqual(app.nodes('HomeScreen')[0].props.dictionaryEntries, []);
assert.equal(app.nodes('DictionaryProvider')[0].props.enabled, false, 'Loading/Home cannot register discoveries');
app.nodes('DictionaryProvider')[0].props.onDiscover('Spin', 'Built-in property.');
app.nodes('HomeScreen')[0].props.onSelectLesson(11); app.nodes('LessonEntryModal')[0].props.onPlay();
app.nodes('LessonNavigationProvider')[0].props.onHome();
assert.deepEqual(app.nodes('HomeScreen')[0].props.dictionaryEntries, one, 'Entries survive navigation');
const home = createHarness('screens/HomeScreen.tsx', { xp: 0, completed: [], onContinue() {}, onSelectLesson() {}, dictionaryEntries: one });
home.nodes('Pressable').find(n => n.props.accessibilityLabel === 'Open your dictionary').props.onPress();
assert.deepEqual(home.nodes('DictionaryModal')[0].props.entries, one);
home.nodes('DictionaryModal')[0].props.onClose(); assert.equal(home.nodes('DictionaryModal').length, 0);
const modal = createHarness('components/DictionaryModal.tsx', { entries: [], onClose() {} });
assert(modal.nodes('Text').some(n => n.children.includes('You haven’t unlocked any words yet!')));
assert(!JSON.stringify(modal.render()).includes('Your collected curiosities'));
assert.equal(modal.nodes('Image').length, 0, 'No decorative book in the empty dictionary');
assert(!modal.nodes('Text').some(n => n.children.includes('Spin')));
const populated = createHarness('components/DictionaryModal.tsx', { entries: [...one, { id: 'atom', term: 'Atom', definition: 'Seen atom definition.' }], onClose() {} });
const rows = populated.all(populated.render()).filter(n => typeof n.type === 'function' && n.type.name === 'RuledEntry');
assert.deepEqual(rows.map(n => n.props.entry.term), ['Atom', 'Spin']);
const homeSource = fs.readFileSync('screens/HomeScreen.tsx', 'utf8');
assert(homeSource.indexOf('styles.achievementCard') < homeSource.indexOf('accessibilityLabel="Open your dictionary"'));
assert(fs.readFileSync('components/TerminologyCard.tsx', 'utf8').includes('watchDictionaryCopy'));
assert(fs.readFileSync('data/preloadAssets.ts', 'utf8').includes("require('../assets/ui/dictionary-source.jpg')"));
console.log('PASS: seen-only dictionary, scroll/background/loading guards, callback cleanup, deduplication, navigation, popup, empty state, alphabetical entries and preload');
