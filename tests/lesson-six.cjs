// Points stay inside the detector; only the isolated case has fringes.
const points = props => {
  const diagram = createHarness('components/ExperimentDiagram.tsx', { mode: 'electron', revealed: true, count: 120, ...props });
  return diagram.nodes('View').filter(n => Array.isArray(n.props.style) && n.props.style[0]?.width === 4).map(n => n.props.style[1]);
};
const isolated = points({}), disturbed = points({ environment: 'air' });
assert.equal(isolated.length, 120); assert.equal(disturbed.length, 120);
assert.notDeepEqual(isolated, disturbed);
assert(disturbed.every(p => p.left >= 0 && p.left + 4 <= 27 && p.top >= 0 && p.top + 4 <= 186));
assert.equal(points({ environment: 'heat' }).length, 120);

