const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const { createHarness } = require('./component-harness.cjs');
const data = {};
new Function('exports', ts.transpileModule(fs.readFileSync('data/achievements.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(data);
const { achievements, initialAchievements, completeAchievementLesson, claimAchievement, recordPacket, openBonusPacket, pendingBonusPackets } = data;
assert.equal(achievements.length, 38);
assert.equal(new Set(achievements.map(a => a.id)).size, 38);
for (const a of achievements) assert(fs.existsSync(`assets/achievements/${a.id}.jpg`));
let p = initialAchievements;
assert.equal(claimAchievement(p, 'W1.1'), p, 'Cannot claim a locked badge');
p = completeAchievementLesson(p, 4);
assert.deepEqual(p.earned, ['W1.1']);
assert.equal(p.quanta, 0, 'Earning is separate from claiming');
p = claimAchievement(p, 'W1.1');
assert.equal(p.quanta, 20);
assert.equal(claimAchievement(p, 'W1.1'), p, 'A duplicate claim is inert');
for (let i = 0; i < 4; i++) p = completeAchievementLesson(p, 4);
assert.equal(p.lessons, 5);
assert.equal(p.completed.length, 1);
assert(p.earned.includes('L1'), 'Replays count towards lessons');
assert.equal(p.earned.filter(id => id === 'W1.1').length, 1);
assert(!p.earned.some(id => id.startsWith('S')), 'No fake login streaks');
for (let i = 0; i < 5; i++) p = recordPacket(p);
assert(p.earned.includes('U1'));
p = claimAchievement(p, 'U1');
assert.deepEqual(pendingBonusPackets(p), ['U1']);
assert.equal(p.quanta, 20, 'Packet rewards do not credit Quanta');
p = openBonusPacket(p, 'U1');
assert.equal(p.packets, 6);
assert.equal(openBonusPacket(p, 'U1'), p);
assert.deepEqual(pendingBonusPackets(p), []);
assert.equal(claimAchievement(p, 'unknown'), p);
for (const a of achievements.filter(a => a.lesson !== undefined)) {
  assert(completeAchievementLesson(initialAchievements, a.lesson).earned.includes(a.id));
}
let allMilestones = initialAchievements;
for (let i = 0; i < 100; i++) allMilestones = completeAchievementLesson(allMilestones, 2);
for (let i = 0; i < 50; i++) allMilestones = recordPacket(allMilestones);
assert.equal(allMilestones.earned.filter(id => id.startsWith('L')).length, 7);
assert.equal(allMilestones.earned.filter(id => id.startsWith('U')).length, 6);
assert.equal(allMilestones.earned.filter(id => id.startsWith('S')).length, 0);
assert.equal(claimAchievement(allMilestones, 'L1').quanta, 20);
for (const badge of achievements.filter(a => a.group === 'Lessons' || a.group === 'Streak' || a.id === 'W2.1')) assert.equal(badge.reward, 20);
const rainbow = claimAchievement(completeAchievementLesson(initialAchievements, 12), 'W2.1');
assert.equal(rainbow.quanta, 20);
assert.equal(claimAchievement(rainbow, 'W2.1'), rainbow);
assert(!completeAchievementLesson(initialAchievements, 27).earned.includes('4.2'));
const family = claimAchievement(completeAchievementLesson(initialAchievements, 28), '4.2');
assert.equal(family.quanta, 30);
assert.equal(claimAchievement(family, '4.2'), family);

const app = createHarness('App.tsx');
const home = () => app.nodes('HomeScreen')[0].props;
home().onSelectLesson(4); app.nodes('LessonEntryModal')[0].props.onPlay();
const finish = app.nodes('LessonFourScreen')[0].props.onComplete;
finish(); finish();
app.nodes('LessonNavigationProvider')[0].props.onHome();
assert.equal(home().achievementCount, 1);
assert.equal(home().unclaimedAchievements, true);
home().onAchievements();
let page = () => app.nodes('AchievementsScreen')[0].props;
assert.equal(page().progress.lessons, 1, 'Completion callback duplicates do not count');
const claim = page().onClaim;
assert.equal(claim('W1.1'), true);
assert.equal(claim('W1.1'), false, 'Rapid stale callback cannot double pay');
assert.equal(page().quanta, 140);
page().onBack();
assert.equal(home().unclaimedAchievements, false);
finish();
assert.equal(home().achievementCount, 1, 'A stale completion does not earn');
for (let i = 0; i < 4; i++) {
  home().onSelectLesson(4); app.nodes('LessonEntryModal')[0].props.onPlay(); app.nodes('LessonFourScreen')[0].props.onComplete();
  app.nodes('LessonNavigationProvider')[0].props.onHome();
}
assert.equal(home().achievementCount, 2);
assert.equal(home().completed.length, 1);
assert.equal(home().xp, 0, 'Achievements never fabricate Knowledge');
for (let i = 0; i < 5; i++) {
  home().onSelectLesson(9); app.nodes('LessonEntryModal')[0].props.onPlay();
  const open = app.nodes('LessonNineScreen')[0].props.onUnlockAccessories;
  open(['fedora']); open(['fedora']);
  app.nodes('LessonNavigationProvider')[0].props.onHome();
  open(['fedora']); // stale event after leaving the lesson
}
home().onAchievements();
assert.equal(page().progress.packets, 5);
assert.equal(page().onClaim('U1'), true);
const openBonus = page().onOpenPacket;
openBonus('U1', ['red-spectacles']); openBonus('U1', ['red-spectacles']);
assert.equal(page().progress.packets, 6);
assert.deepEqual(page().progress.openedBonus, ['U1']);
const notice = page().progress.notices[0];
const dismiss = page().onDismissNotice;
dismiss(notice); dismiss(notice);
assert.equal(page().progress.notices.length, 2, 'Stale dismissal cannot skip a queued toast');
app.nodes('KnowledgeProvider')[0].props.onCorrect('not-a-lesson');
assert.equal(app.nodes('DictionaryProvider')[0].props.enabled, false);
page().onBack(); assert.equal(home().xp, 0);

