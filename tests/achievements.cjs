toast.render(); assert.deepEqual(toast.pendingTimeouts(), [3500]);
toast.timeout(); assert.deepEqual(dismissed, ['W1.1']);
toastProps.id = 'L1'; toast.render(); toast.unmount();
assert.deepEqual(toast.pendingTimeouts(), [], 'Toast timers clean up');
const toastPaused = createHarness('components/AchievementToast.tsx', { ...toastProps, enabled: false });
toastPaused.render(); assert.deepEqual(toastPaused.pendingTimeouts(), []);
