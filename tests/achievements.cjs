bonusPage.nodes('Pressable').find(n => n.props.accessibilityLabel?.startsWith('5 packets opened.')).props.onPress({ nativeEvent: { pageX: 50, pageY: 200 } });
assert.equal(bonusPage.nodes('Modal')[0].props.visible, true, 'Claiming a bonus packet opens it directly');
bonusPage.nodes('Pressable').find(n => n.children.some(c => c?.children?.includes('Close'))).props.onPress();
assert.equal(bonusPage.nodes('Modal')[0].props.visible, false);
