assert.equal(emptyPage.nodes('View').filter(n => n.props.accessibilityLabel === 'Mystery achievement, locked').length, 15);
const serialized = JSON.stringify(emptyPage.render());
assert(!serialized.includes('Superpose'));
assert(!serialized.includes('Cat’s out of the bag'), 'Locked world names must not leak into accessibility');
assert(serialized.includes('365-day streak'));
assert(serialized.includes('100 lessons completed'));
