const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const { createHarness } = require('./component-harness.cjs');
const data = {};
new Function('exports', ts.transpileModule(fs.readFileSync('data/knowledge.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(data);
const { initialKnowledge, earnKnowledge, presentKnowledge, knowledgeLevel } = data;
assert.equal(knowledgeLevel(0), 1);
assert.equal(knowledgeLevel(199), 1);
assert.equal(knowledgeLevel(200), 2);
assert.equal(earnKnowledge(initialKnowledge).total, 5);
let p = { ...initialKnowledge, total: 415 };
p = presentKnowledge(p, 200);
assert.deepEqual([p.shown, p.quanta, p.celebrations], [200, 140, [2]]);
assert.deepEqual(presentKnowledge(p, 200), p, 'No duplicate level reward');
p = presentKnowledge(p, 999);
assert.deepEqual([p.shown, p.quanta, p.celebrations], [415, 160, [2, 3]]);
assert.deepEqual(presentKnowledge(p, 0), p, 'Presentation never moves backwards');

const questions = [{ question: 'One?', options: ['Yes', 'No'], answer: 'Yes' }, { question: 'Two?', options: ['Yes', 'No'], answer: 'No' }];
let failed = 0;
const quiz = createHarness('components/LessonQuiz.tsx', { questions, minimumCorrect: 2, onFinish() { throw Error('Should not pass'); }, onNotPassed() { failed++; } });
let choose = quiz.nodes('QuizQuestion')[0].props.onSelect;
choose('Yes'); choose('Yes');
assert.equal(quiz.rewards.length, 1);
quiz.nodes('PrimaryButton')[0].props.onPress();
choose = quiz.nodes('QuizQuestion')[0].props.onSelect;
choose('Yes'); choose('No');
assert.equal(quiz.rewards.length, 1, 'Wrong first answer and later taps earn nothing');
quiz.nodes('PrimaryButton')[0].props.onPress();
assert.equal(failed, 1);

// App ledger: answer-time earning, not completion-time bonuses. Replay is fresh.
const app = createHarness('App.tsx');
const home = () => app.nodes('HomeScreen')[0].props;
home().onSelectLesson(2); app.nodes('LessonEntryModal')[0].props.onPlay(); app.render();
const award = app.nodes('KnowledgeProvider')[0].props.onCorrect;
award('quiz:0'); award('quiz:0');
app.nodes('LessonTwoScreen')[0].props.onComplete(3);
app.nodes('LessonNavigationProvider')[0].props.onHome();
assert.equal(home().xp, 5);
assert.equal(home().shownKnowledge, 0);
award('late callback');
assert.equal(home().xp, 5, 'Stale lesson callbacks cannot earn');
home().onKnowledgePresented(5);
assert.equal(home().shownKnowledge, 5);
home().onSelectLesson(2); app.nodes('LessonEntryModal')[0].props.onPlay(); app.render();
app.nodes('KnowledgeProvider')[0].props.onCorrect('quiz:0');
for (let i = 1; i < 80; i++) app.nodes('KnowledgeProvider')[0].props.onCorrect(`quiz:${i}`);
app.nodes('LessonNavigationProvider')[0].props.onHome();
assert.equal(home().xp, 405);
home().onKnowledgePresented(200); home().onKnowledgePresented(200);
assert.equal(home().quanta, 140);
assert.equal(home().levelUp, 2);
home().onKnowledgePresented(400);
const close = home().onDismissLevelUp;
close(2); close(2);
assert.equal(home().levelUp, 3, 'Rapid dismissal must not skip the next celebration');
assert.equal(home().quanta, 160);
close(3);
assert.equal(home().levelUp, undefined);

const props = { value: 415, from: 190, enabled: true, onPresented: value => steps.push(value) };
const steps = [];
const bar = createHarness('components/XPBar.tsx', props);
bar.render();
for (let i = 0; i < 45; i++) bar.tick();
assert.deepEqual(steps, [200], 'Animation pauses at the first level boundary');
assert.equal(bar.activeTimers(), 0);
props.from = 200; props.enabled = false; bar.render(); bar.tick();
assert.deepEqual(steps, [200], 'No hidden animation behind a modal');
props.enabled = true; bar.render();
for (let i = 0; i < 45; i++) bar.tick();
assert.deepEqual(steps, [200, 400]);
props.from = 400; bar.render(); bar.tick(); bar.unmount();
assert.equal(bar.activeTimers(), 0, 'Leaving Home cancels presentation');

