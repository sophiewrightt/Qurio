const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const { createHarness } = require('./component-harness.cjs');
const data = {};
const curriculum = {}; new Function('exports', ts.transpileModule(fs.readFileSync('data/curriculum.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(curriculum);
new Function('require', 'exports', ts.transpileModule(fs.readFileSync('data/lessonEntry.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(() => curriculum, data);
const { lessonOrder, availableLessonIds } = data;
for (let n = 0; n <= lessonOrder.length; n++) {
  const completed = lessonOrder.slice(0, n);
  const visible = availableLessonIds(completed);
  assert.deepEqual(visible, lessonOrder.slice(0, Math.min(n + 1, lessonOrder.length)));
  const home = createHarness('screens/HomeScreen.tsx', { xp: 0, collected: false, completed, visibleLessons: visible });
  const rows = home.nodes('TourAnchor').filter(node => node.props.id.startsWith('lesson-')).map(node => Number(node.props.id.slice(7)));
  assert.deepEqual(rows, visible, 'Only the completed path and next lesson render, across all four worlds');
  const text = home.nodes('Text').flatMap(n => n.children);
  assert.equal(text.includes('CHAPTER 2'), visible.includes(11));
  assert.equal(text.includes('CHAPTER 3'), visible.includes(19));
  assert.equal(text.includes('CHAPTER 4'), visible.includes(26));
}
assert.deepEqual(availableLessonIds([2, 31]), [1], 'Out-of-order completion cannot skip prerequisites');
const unrestricted = createHarness('screens/HomeScreen.tsx', { xp: 0, collected: false, completed: [] });
assert.equal(unrestricted.nodes('TourAnchor').filter(n => n.props.id.startsWith('lesson-')).length, 31);
const guest = createHarness('App.tsx', { profile: { username: 'Guest', mode: 'guest' } });
const home = () => guest.nodes('HomeScreen')[0].props;
assert.deepEqual(home().visibleLessons, [1]);
for (const id of [2, 9, 11, 31, 26, 32]) { home().onSelectLesson(id); assert.equal(guest.nodes('LessonEntryModal').length, 0); }
home().onSelectLesson(1); guest.nodes('LessonEntryModal')[0].props.onPlay();
guest.nodes('LessonScreen')[0].props.onComplete(); guest.nodes('LessonNavigationProvider')[0].props.onHome();
assert.deepEqual(home().visibleLessons, [1, 2]);
home().onSelectLesson(2); guest.nodes('LessonEntryModal')[0].props.onPlay();
// Exercise the real finish controls against App's navigation and cancellation state.
let completions = 0;
const props = { tourContext: guest.nodes('LessonNavigationProvider')[0].props, onComplete() { completions++; guest.nodes('LessonTwoScreen')[0].props.onComplete(); } };
const controls = createHarness('components/LessonFinishActions.tsx', props);
const press = label => controls.nodes('Pressable').find(n => n.props.accessibilityLabel === label).props.onPress();
press('Next lesson'); press('Next lesson');
assert.equal(guest.nodes('LessonEntryModal')[0].props.lesson, '1.3');
assert.equal(completions, 1);
const stalePlay = guest.nodes('LessonEntryModal')[0].props.onPlay;
guest.nodes('LessonEntryModal')[0].props.onLater();
props.tourContext = guest.nodes('LessonNavigationProvider')[0].props;
press('Next lesson');
assert.equal(guest.nodes('LessonEntryModal')[0].props.lesson, '1.3', 'Next works after Later');
stalePlay(); assert.equal(guest.nodes('LessonEntryModal').length, 1, 'Old dialog cannot accept the new one');
guest.nodes('LessonEntryModal')[0].props.onLater();
props.tourContext = guest.nodes('LessonNavigationProvider')[0].props;
press('Back to home');
assert.equal(guest.nodes('HomeScreen').length, 1, 'Home works after Later');
assert.equal(completions, 1, 'Cancelled admission never repeats completion rewards');
assert.deepEqual(home().visibleLessons, [1, 2, 3]);
const tester = createHarness('App.tsx', { profile: { username: 'Creator', mode: 'tester' } });
assert.equal(tester.nodes('HomeScreen')[0].props.visibleLessons, undefined);
tester.nodes('HomeScreen')[0].props.onSelectLesson(32);
assert.equal(tester.nodes('ModuleFourLessonSixScreen').length, 1);
const greeting = createHarness('components/AvatarGreeting.tsx', { enabled: true });
greeting.render(); assert.equal(greeting.nodes('Image').length, 0);
assert(greeting.nodes('View').some(n => n.props.style?.borderBottomLeftRadius === 22));
const unlock = createHarness('components/WorldUnlockModal.tsx', { world: 2 });
assert(unlock.nodes('View').some(n => n.props.style?.gap === 20));
console.log('PASS: sequential guest visibility and admission, unchanged creator access, Next/Later/Next and Next/Later/Home recovery, one completion, curved greeting and spaced world actions');
