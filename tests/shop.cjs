const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const { createHarness } = require('./component-harness.cjs');
const data = {};
new Function('exports', ts.transpileModule(fs.readFileSync('data/shop.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(data);
const { initialShop, buyPacket, ripPacket, finishPacket, eligibleAccessories, packetOffers } = data;
const catalog = ['a', 'b', 'c', 'd', 'e', 'lips', 'curly-moustache', 'deal-with-it-glasses'].map(id => ({ id, name: id, category: 'eyes', source: id }));
assert.deepEqual(packetOffers.map(p => p.price), [100, 200, 350, 500]);
for (const kind of ['rare', 'ultra-rare', 'legendary']) {
  assert.equal(eligibleAccessories(kind, catalog.slice(0, 5), []).length, 0, 'Unassigned items default to Common');
  assert.equal(buyPacket(initialShop, kind, 999, catalog.slice(0, 5), []), initialShop);
}
assert.equal(buyPacket(initialShop, 'standard', 99, catalog, []), initialShop);
assert.equal(buyPacket(initialShop, 'standard', 100, catalog, catalog.map(i => i.id)).packet.rewards.length, 3, 'Full collections can still buy');
let state = buyPacket(initialShop, 'standard', 120, catalog, ['a'], () => 0.2);
assert.equal(state.spent, 100);
assert.equal(state.packet.rewards.length, 3);
assert.equal(new Set(state.packet.rewards).size, 1, 'Draws use replacement');
assert(!state.packet.rewards.includes('a'));
assert.equal(buyPacket(state, 'standard', 999, catalog, []), state, 'Cannot buy again while pending');
assert.equal(finishPacket(state, state.packet.id), state, 'Cannot discard an unopened purchase');
assert.equal(ripPacket(state, 55), state);
state = ripPacket(state, state.packet.id);
assert.equal(ripPacket(state, state.packet.id), state);
const oldId = state.packet.id;
state = finishPacket(state, oldId);
assert(!state.packet);
assert.equal(buyPacket(state, 'standard', 120, catalog, []), state, 'Spending is deducted from total earnings');
state = buyPacket(state, 'standard', 500, catalog, ['a', 'b', 'c', 'd'], () => 0);
assert.deepEqual(state.packet.rewards, ['a', 'a', 'a'], 'Owned items and same-packet repeats remain eligible');
assert.notEqual(state.packet.id, oldId);
assert.equal(ripPacket(state, oldId), state, 'An earlier rip cannot open a later purchase');
const rarities = { a: 'rare', b: 'ultra-rare', c: 'legendary', d: 'rare' };
for (const kind of ['rare', 'ultra-rare', 'legendary']) {
  const purchase = buyPacket(initialShop, kind, 1000, catalog, [], () => 0, rarities);
  assert.equal(purchase.packet.rewards.length, 1);
  assert.equal(rarities[purchase.packet.rewards[0]], kind);
}

const app = createHarness('App.tsx');
const home = () => app.nodes('HomeScreen')[0].props;
home().onCustomise();
app.nodes('CustomisationScreen')[0].props.onShop();
const shop = () => app.nodes('ShopScreen')[0].props;
assert.equal(shop().quanta, 120);
const buy = shop().onBuy;
assert.equal(buy('rare'), false);
assert.equal(buy('standard'), true);
assert.equal(buy('standard'), false, 'Double tap charges once');
assert.equal(shop().quanta, 20);
assert.deepEqual(shop().owned, [], 'Buying does not unlock before ripping');
const packet = shop().packet;
shop().onBack();
app.nodes('CustomisationScreen')[0].props.onBack();
home().onSelectLesson(9); app.nodes('LessonEntryModal')[0].props.onPlay();
assert.deepEqual(app.nodes('LessonNineScreen')[0].props.ownedAccessories, [], 'Unopened items are not owned or excluded');
app.nodes('LessonNavigationProvider')[0].props.onHome();
home().onAchievements();
assert.deepEqual(app.nodes('AchievementsScreen')[0].props.owned, [], 'Bonus packets use actual ownership only');
app.nodes('AchievementsScreen')[0].props.onBack(); home().onCustomise();
app.nodes('CustomisationScreen')[0].props.onShop();
assert.deepEqual(shop().packet, packet, 'Navigation preserves the exact purchase');
const rip = shop().onRip;
rip(packet.id); rip(packet.id);
assert.equal(shop().owned.length, new Set(packet.rewards).size, 'Inventory deduplicates repeated rewards');
shop().onFinishPacket(packet.id);
assert.equal(shop().packet, undefined);
assert.equal(shop().onBuy('standard'), false, 'Insufficient funds cannot spend');
shop().onBack(); app.nodes('CustomisationScreen')[0].props.onBack();
assert.equal(home().quanta, 20);
home().onAchievements();
assert.equal(app.nodes('AchievementsScreen')[0].props.progress.packets, 1, 'Only one actual opening recorded');

const props = { quanta: 120, owned: [], onBuy: () => true, onRip() {}, onFinishPacket() {}, onBack() {} };
const ui = createHarness('screens/ShopScreen.tsx', props);
const buttons = () => ui.nodes('Pressable');
assert(!buttons().find(n => n.props.accessibilityLabel === 'Buy Q accessory packet for 100 Quanta').props.disabled);
for (const rarity of ['Rare', 'Ultra Rare', 'Legendary']) assert(buttons().find(n => n.props.accessibilityLabel?.startsWith(`Buy ${rarity} packet`)).props.disabled);
assert.equal(ui.nodes('QuantaArtwork').length, 4);
assert(!buttons().some(n => /A\$/.test(n.props.accessibilityLabel || '')), 'No pretend real-money checkout');
const pack = createHarness('components/RewardPack.tsx', { rewardIds: ['fedora'], onOpen(ids) { assert.deepEqual(ids, ['fedora']); } });
pack.nodes('PrimaryButton')[0].props.onPress();
assert(pack.nodes('Text').some(n => n.children.includes('Here’s what you got!')));
const resumed = createHarness('components/RewardPack.tsx', { rewardIds: ['fedora'], initiallyOpen: true });
assert.equal(resumed.nodes('PrimaryButton').length, 0, 'An opened purchase resumes its results, not another rip');
const thankYou = createHarness('screens/ShopScreen.tsx', { visible: true, onClose() {} }, 'PurchaseThankYouModal');
assert(thankYou.nodes('Text').some(n => n.children.includes('Thank you! Your support means a lot.')));
for (const file of fs.readdirSync('assets/shop')) assert(fs.readFileSync('data/preloadAssets.ts', 'utf8').includes(file));
console.log('PASS: boutique shop, prices, Common defaults, exact-rarity selection, purchase debit, stable pending packets, one-time openings, and disabled IAP');
