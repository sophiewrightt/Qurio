const assert = require('node:assert/strict');
const fs = require('node:fs');
const { createHarness } = require('./component-harness.cjs');
const screen = createHarness('screens/LessonFiveScreen.tsx', { onHome() {}, onComplete() {} });
assert.equal(screen.nodes('ElectronRun').length, 1);
assert.equal(screen.nodes('MysteryPanel').length, 0);
assert(!screen.nodes('PrimaryButton').some(n => /Add slit detectors|Without detectors/.test(n.props.label)));
assert(JSON.stringify(screen.render()).includes('We KNOW now'));
assert(JSON.stringify(screen.render()).includes('Do they somehow know to make this pattern?'));
screen.nodes('ElectronRun')[0].props.onPattern();
assert.equal(screen.nodes('ElectronRun').length, 2, 'Second independent experiment reveals after first pattern');
assert.equal(screen.nodes('ElectronRun')[0].props.whichPath, undefined);
assert.equal(screen.nodes('ElectronRun')[1].props.whichPath, true);
assert.equal(screen.nodes('MysteryPanel').length, 0, 'Explanation waits for second pattern');
assert(JSON.stringify(screen.render()).includes('Exactly as before, we have alternating bands'));
screen.nodes('ElectronRun')[1].props.onPattern();
assert.equal(screen.nodes('MysteryPanel').length, 0, 'Chapter 1 no longer inserts separate quantum mystery cards');
const lessonFiveSource = fs.readFileSync('screens/LessonFiveScreen.tsx', 'utf8');
assert(lessonFiveSource.includes('<WizardMagicScene />'));
assert(lessonFiveSource.includes('<MagicHatScene />'));
assert(JSON.stringify(screen.render()).includes('really'));
assert(screen.nodes('HoveringImage').some(n => String(n.props.source).includes('conscious-electron-transparent.png')));
assert(screen.nodes('PrimaryButton').some(n => n.props.label === 'Start the quiz'));
screen.nodes('PrimaryButton').find(n => n.props.label === 'Start the quiz').props.onPress();
assert.equal(screen.nodes('LessonQuiz').length, 1);
assert(fs.readFileSync('data/lessonFive.ts', 'utf8').includes('lessonFiveQuestions'));

let completions = 0;
const busy = [];
const run = createHarness('components/ElectronRun.tsx', { onPattern: () => completions++, onBusyChange: value => busy.push(value) });
const button = label => run.nodes('PrimaryButton').find(n => n.props.label === label);
const count = () => run.nodes('ExperimentDiagram')[0].props.count;
assert.equal(count(), 0);
const fire = button('Shoot an electron').props.onPress;
fire(); fire();
assert(run.nodes('PrimaryButton').every(n => n.props.disabled));
run.flight();
assert.equal(count(), 1);
assert.equal(run.peekFlight(), undefined, 'Rapid double tap schedules only one shot');
assert.equal(run.nodes('PrimaryButton').length, 1);
assert.equal(button('Fire many · build the pattern'), undefined, 'Three individual arrivals precede pattern building');
for (let i = 0; i < 2; i++) { button('Shoot an electron').props.onPress(); run.flight(); }
assert.equal(button('Shoot an electron'), undefined);
button('Fire many · build the pattern').props.onPress();
run.flight();
for (let i = 0; i < 12; i++) run.tick();
assert.equal(count(), 64);
assert.equal(completions, 1);
button('Fire many · build the pattern').props.onPress(); run.flight();
for (let i = 0; i < 12; i++) run.tick();
assert.equal(count(), 120);
assert.equal(completions, 1, 'Pattern callback only once per run');
assert(run.nodes('PrimaryButton').every(n => n.props.disabled));
assert.deepEqual(busy, [true, false, true, false, true, false, true, false, true, false]);
const second = createHarness('components/ElectronRun.tsx', { whichPath: true, onPattern() {} });
assert.equal(second.nodes('ExperimentDiagram')[0].props.count, 0, 'Second component has a fresh empty screen');
assert.equal(count(), 120, 'First screen retains its own arrivals');
for (let i = 0; i < 4; i++) { second.nodes('PrimaryButton')[0].props.onPress(); second.flight(); }
assert.equal(second.activeTimers(), 1);
second.unmount(); assert.equal(second.activeTimers(), 0, 'Unmount cancels accumulation');
const canceled = createHarness('components/ElectronRun.tsx', { onPattern() {} });
canceled.nodes('PrimaryButton')[0].props.onPress(); canceled.flight(false);
assert(!canceled.nodes('PrimaryButton')[0].props.disabled, 'Interrupted animation releases the controls');
canceled.nodes('PrimaryButton')[0].props.onPress();
const lateFlight = canceled.peekFlight(); canceled.unmount(); lateFlight({ finished: true });
assert.equal(canceled.nodes('ExperimentDiagram')[0].props.count, 0, 'Late flight does not update an unmounted experiment');
console.log('PASS: sequential experiments, independent counts, rapid taps, completion gates, cancellation and cleanup');
